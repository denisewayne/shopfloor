/**
 * Generate SuiteCloud (SDF) object XML from src/netsuite/deploy/manifest.ts.
 *
 *   npm run sdf          write suitecloud/src/Objects/*.xml
 *   npm run sdf -- --check  fail if the committed XML is out of date (CI)
 *
 * Every deployment is generated in a safe state: status NOTSCHEDULED for
 * scheduled scripts (nothing runs until you schedule it in the UI or edit
 * the XML) and TESTING for RESTlets (only the script owner can call it).
 */
import * as fs from 'fs';
import * as path from 'path';
import { FILE_CABINET_ROOT, ParamSpec, SCRIPTS, ScriptSpec } from '../src/netsuite/deploy/manifest';

const OUT_DIR = path.resolve(__dirname, '..', 'suitecloud', 'src', 'Objects');

const LIMITS = { scriptId: 40, deploymentId: 40, paramId: 30, label: 200 };

export function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export function validate(scripts: Record<string, ScriptSpec>): string[] {
  const errors: string[] = [];
  const seenParams = new Map<string, string>();
  const seenIds = new Set<string>();

  for (const [key, s] of Object.entries(scripts)) {
    if (!/^customscript_[a-z0-9_]+$/.test(s.scriptId)) errors.push(`${key}: scriptId must match customscript_[a-z0-9_]+`);
    if (!/^customdeploy_[a-z0-9_]+$/.test(s.deploymentId)) errors.push(`${key}: deploymentId must match customdeploy_[a-z0-9_]+`);
    if (s.scriptId.length > LIMITS.scriptId) errors.push(`${key}: scriptId over ${LIMITS.scriptId} chars`);
    if (s.deploymentId.length > LIMITS.deploymentId) errors.push(`${key}: deploymentId over ${LIMITS.deploymentId} chars`);
    for (const id of [s.scriptId, s.deploymentId]) {
      if (seenIds.has(id)) errors.push(`${key}: duplicate id ${id}`);
      seenIds.add(id);
    }
    for (const p of Object.values(s.params) as ParamSpec[]) {
      if (!/^custscript_[a-z0-9_]+$/.test(p.id)) errors.push(`${key}: param ${p.id} must match custscript_[a-z0-9_]+`);
      if (p.id.length > LIMITS.paramId) errors.push(`${key}: param ${p.id} over ${LIMITS.paramId} chars`);
      if (p.label.length > LIMITS.label) errors.push(`${key}: param ${p.id} label too long`);
      const owner = seenParams.get(p.id);
      if (owner) errors.push(`${key}: param ${p.id} already used by ${owner} (ids are account-wide)`);
      seenParams.set(p.id, key);
    }
  }
  return errors;
}

function paramXml(p: ParamSpec): string {
  const isCheckbox = p.type === 'CHECKBOX';
  return [
    `    <scriptcustomfield scriptid="${p.id}">`,
    `      <accesslevel>2</accesslevel>`,
    `      <applyformatting>F</applyformatting>`,
    `      <checkspelling>F</checkspelling>`,
    `      <defaultchecked>${isCheckbox && p.defaultChecked ? 'T' : 'F'}</defaultchecked>`,
    !isCheckbox && p.defaultValue !== undefined ? `      <defaultvalue>${esc(p.defaultValue)}</defaultvalue>` : null,
    `      <description>${esc(p.help)}</description>`,
    `      <displaytype>NORMAL</displaytype>`,
    `      <fieldtype>${p.type}</fieldtype>`,
    `      <help>${esc(p.help)}</help>`,
    `      <isformula>F</isformula>`,
    `      <ismandatory>F</ismandatory>`,
    `      <label>${esc(p.label)}</label>`,
    `      <onparentdelete>NO_ACTION</onparentdelete>`,
    `      <searchlevel>2</searchlevel>`,
    `      <storevalue>T</storevalue>`,
    `    </scriptcustomfield>`,
  ]
    .filter((l) => l !== null)
    .join('\n');
}

export function scriptXml(s: ScriptSpec): string {
  const params = Object.values(s.params) as ParamSpec[];
  const status = s.kind === 'scheduledscript' ? 'NOTSCHEDULED' : 'TESTING';
  return [
    `<!-- Generated by scripts/generate-sdf.ts from src/netsuite/deploy/manifest.ts. Do not edit by hand. -->`,
    `<${s.kind} scriptid="${s.scriptId}">`,
    `  <description>${esc(s.description)}</description>`,
    `  <isinactive>F</isinactive>`,
    `  <name>${esc(s.name)}</name>`,
    `  <notifyowner>T</notifyowner>`,
    `  <scriptfile>[${FILE_CABINET_ROOT}/${s.file}]</scriptfile>`,
    params.length ? `  <scriptcustomfields>\n${params.map(paramXml).join('\n')}\n  </scriptcustomfields>` : null,
    `  <scriptdeployments>`,
    `    <scriptdeployment scriptid="${s.deploymentId}">`,
    `      <isdeployed>T</isdeployed>`,
    `      <loglevel>AUDIT</loglevel>`,
    `      <status>${status}</status>`,
    `      <title>${esc(s.name)}</title>`,
    `    </scriptdeployment>`,
    `  </scriptdeployments>`,
    `</${s.kind}>`,
    ``,
  ]
    .filter((l) => l !== null)
    .join('\n');
}

export function render(scripts: Record<string, ScriptSpec>): Record<string, string> {
  const files: Record<string, string> = {};
  for (const s of Object.values(scripts)) files[`${s.scriptId}.xml`] = scriptXml(s);
  return files;
}

function main(): void {
  const check = process.argv.includes('--check');
  const scripts = SCRIPTS as unknown as Record<string, ScriptSpec>;

  const errors = validate(scripts);
  if (errors.length) {
    for (const e of errors) console.error(`  ${e}`);
    process.exit(1);
  }

  const buildRoot = path.resolve(__dirname, '..', 'build');
  if (fs.existsSync(buildRoot)) {
    for (const s of Object.values(scripts)) {
      if (!fs.existsSync(path.join(buildRoot, s.file))) {
        console.error(`  ${s.scriptId}: ${s.file} not found in build/. Did the script move?`);
        process.exit(1);
      }
    }
  }

  const files = render(scripts);
  const generated = new Set(Object.keys(files));
  fs.mkdirSync(OUT_DIR, { recursive: true });

  let stale = 0;
  for (const [name, xml] of Object.entries(files)) {
    const target = path.join(OUT_DIR, name);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === xml) continue;
    stale++;
    if (check) console.error(`  out of date: suitecloud/src/Objects/${name}`);
    else fs.writeFileSync(target, xml);
  }

  // Remove XML for scripts that were dropped from the manifest (only files we generated).
  for (const name of fs.readdirSync(OUT_DIR)) {
    if (!name.startsWith('customscript_sf_') || generated.has(name)) continue;
    stale++;
    if (check) console.error(`  orphaned: suitecloud/src/Objects/${name}`);
    else fs.unlinkSync(path.join(OUT_DIR, name));
  }

  if (check && stale) {
    console.error('SDF objects are out of date. Run: npm run sdf');
    process.exit(1);
  }
  console.log(`SDF objects: ${generated.size} script(s) ${check ? 'up to date' : `written to suitecloud/src/Objects (${stale} changed)`}`);
}

if (require.main === module) main();
